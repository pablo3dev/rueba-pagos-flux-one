#!/bin/sh
# Rol y esquema de auditoría para desarrollo de esta unidad.
set -eu
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<EOSQL
REVOKE CREATE, USAGE ON SCHEMA public FROM PUBLIC;
REVOKE CONNECT ON DATABASE ${POSTGRES_DB} FROM PUBLIC;
CREATE ROLE audit_svc LOGIN PASSWORD '${AUDIT_DB_PASSWORD}' NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT;
GRANT CONNECT ON DATABASE ${POSTGRES_DB} TO audit_svc;
CREATE SCHEMA audit_schema AUTHORIZATION audit_svc;
REVOKE ALL ON SCHEMA audit_schema FROM PUBLIC;
ALTER ROLE audit_svc IN DATABASE ${POSTGRES_DB} SET search_path = audit_schema;
EOSQL
